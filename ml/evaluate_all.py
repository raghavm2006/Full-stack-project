"""
Phase 11: consolidated model evaluation report.

Phase 6's train.py scripts each save their own models_store/<task>/
metrics.json (accuracy/precision/recall/F1 for every algorithm compared,
plus which one won). This script reads all three, builds one
side-by-side comparison, and writes it out as both a human-readable
Markdown report (models_store/evaluation_summary.md — meant to be
pasted straight into a project report) and a machine-readable JSON file
(models_store/evaluation_summary.json).

Deliberately a plain offline script under ml/, not a Flask route —
consistent with rule #3/#14/#15 (training/evaluation stays out of the
web request path). Run it any time after Phase 6's training, and again
after retraining, to refresh the summary:

    python -m ml.evaluate_all
"""

import json
import os

MODELS_DIR = "models_store"

TASKS = [
    ("categorization", "Categorization (Work / Personal / Other)"),
    ("spam", "Spam Detection (ham / spam)"),
    ("priority", "Priority Detection (LOW / MEDIUM / HIGH)"),
]

CAVEATS = {
    "categorization": (
        "Trained on 3 classes derived from the Enron corpus's Berkeley "
        "taxonomy (Work/Personal/Other) rather than all 9 of EmailOrbit's "
        "target categories — Enron has no real Finance/Shopping/Travel/"
        "Social/Promotions examples. A documented, deliberate scope "
        "decision, not a hidden shortcut."
    ),
    "spam": None,
    "priority": (
        "Trained on heuristic pseudo-labels (see "
        "ml/priority_detection/feature_engineering.py), not real-world "
        "ground truth — no labeled priority dataset exists. These "
        "metrics measure agreement with the heuristic rule, not "
        "real-world urgency judgment."
    ),
}


def load_task_metrics(task: str):
    path = os.path.join(MODELS_DIR, task, "metrics.json")
    if not os.path.exists(path):
        return None
    with open(path) as f:
        return json.load(f)


def build_summary() -> dict:
    summary = {"tasks": {}}

    for task, _label in TASKS:
        metrics = load_task_metrics(task)
        if metrics is None:
            summary["tasks"][task] = {"trained": False}
            continue

        summary["tasks"][task] = {
            "trained": True,
            "best_model": metrics["best_model"],
            "models_compared": {
                name: {
                    "accuracy": result["accuracy"],
                    "precision_weighted": result["precision_weighted"],
                    "recall_weighted": result["recall_weighted"],
                    "f1_weighted": result["f1_weighted"],
                }
                for name, result in metrics["results"].items()
            },
            "caveat": CAVEATS.get(task),
        }

    return summary


def render_markdown(summary: dict) -> str:
    lines = ["# EmailOrbit — Model Evaluation Summary", ""]
    lines.append(
        "Generated by `python -m ml.evaluate_all` from each task's "
        "`models_store/<task>/metrics.json` (produced by Phase 6's "
        "`train.py` scripts). Re-run after retraining to refresh this file."
    )
    lines.append("")

    any_trained = False

    for task, label in TASKS:
        task_summary = summary["tasks"][task]
        lines.append(f"## {label}")
        lines.append("")

        if not task_summary["trained"]:
            lines.append(
                "_Not yet trained._ Run `python -m ml.{0}.preprocess` and "
                "`python -m ml.{0}.train` first.".format(task)
            )
            lines.append("")
            continue

        any_trained = True
        best_model = task_summary["best_model"]

        lines.append("| Model | Accuracy | Precision (weighted) | Recall (weighted) | F1 (weighted) |")
        lines.append("|---|---|---|---|---|")
        for name, result in task_summary["models_compared"].items():
            marker = " **(best)**" if name == best_model else ""
            lines.append(
                f"| {name}{marker} | {result['accuracy']:.3f} | "
                f"{result['precision_weighted']:.3f} | {result['recall_weighted']:.3f} | "
                f"{result['f1_weighted']:.3f} |"
            )
        lines.append("")

        if task_summary["caveat"]:
            lines.append(f"**Caveat:** {task_summary['caveat']}")
            lines.append("")

    if not any_trained:
        lines.append(
            "No tasks have been trained yet — run Phase 6's preprocess/"
            "train scripts for at least one task, then re-run this script."
        )
        lines.append("")

    return "\n".join(lines)


def main():
    summary = build_summary()

    os.makedirs(MODELS_DIR, exist_ok=True)

    json_path = os.path.join(MODELS_DIR, "evaluation_summary.json")
    with open(json_path, "w") as f:
        json.dump(summary, f, indent=2)
    print(f"Saved {json_path}")

    markdown = render_markdown(summary)
    md_path = os.path.join(MODELS_DIR, "evaluation_summary.md")
    with open(md_path, "w", encoding="utf-8") as f:
        f.write(markdown)
    print(f"Saved {md_path}")

    print()
    print(markdown)


if __name__ == "__main__":
    main()
